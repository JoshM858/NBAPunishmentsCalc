// Bundles the whole site into one file you can paste into the Cloudflare dashboard editor.
// Usage: node scripts/build-dashboard.mjs [out-file]  ->  dist/worker-dashboard.js
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const read = (p) => readFileSync(new URL(p, root), 'utf8');
const types = { html: 'text/html; charset=utf-8', css: 'text/css; charset=utf-8', js: 'text/javascript; charset=utf-8' };

const files = Object.fromEntries(
  ['index.html', 'styles.css', 'app.js', 'logic.js', 'pipeline.js', 'sources.js', 'trade.js', 'trade-ui.js', 'demo.js'].map((f) => [`/${f}`, [types[f.split('.').pop()], read(`public/${f}`)]]),
);
const api = read('src/api.js').replace('export async function handleApi', 'async function handleApi');

const out = `// Punishment Watch — single-file Worker for the Cloudflare dashboard.
// Paste this whole file into the Worker's code editor and deploy.
// Settings > Variables and Secrets: LEAGUE_ID (text), SEASON (text, 2027),
// ESPN_S2 and ESPN_SWID (secrets, optional if the league is public), HIDE_TEAMS (text, optional).
// Generated by scripts/build-dashboard.mjs — edit the source files, not this one.

${api}
const FILES = ${JSON.stringify(files)};

export default {
  async fetch(request, env, ctx) {
    const { pathname } = new URL(request.url);
    if (pathname.startsWith('/api/')) return handleApi(request, env, ctx);
    const file = FILES[pathname === '/' ? '/index.html' : pathname];
    if (!file) return new Response('Not found', { status: 404 });
    return new Response(file[1], { headers: { 'content-type': file[0], 'cache-control': 'public, max-age=300' } });
  },
};
`;

const target = process.argv[2] ? resolve(process.argv[2]) : fileURLToPath(new URL('dist/worker-dashboard.js', root));
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, out);
console.log(`${target.replace(fileURLToPath(root), '')} ${(out.length / 1024).toFixed(1)} KB`);
